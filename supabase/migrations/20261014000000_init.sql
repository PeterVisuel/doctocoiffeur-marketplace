-- -------------------------------------------------------------------------------------
-- Tables
-- -------------------------------------------------------------------------------------

-- Un profil par compte (client, prestataire ou administrateur)
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'client' check (role in ('client', 'prestataire', 'admin')),
  email text not null,
  first_name text not null default '',
  last_name text not null default '',
  phone text not null default '',
  referral_code text unique,
  referred_by uuid references public.profiles (id) on delete set null,
  sponsor_rewarded boolean not null default false,
  created_at timestamptz not null default now()
);

-- Salons / prestataires. Prestations, horaires et photos restent en JSON (même format que le site).
create table if not exists public.prestataires (
  id bigint generated by default as identity primary key,
  owner_id uuid unique references auth.users (id) on delete set null,
  name text not null,
  city text not null,
  category text not null check (category in ('Beauté', 'Artisans')),
  email text not null default '',
  approved boolean not null default false,
  services jsonb not null default '[]'::jsonb,
  schedule jsonb not null default '{}'::jsonb,
  photos jsonb not null default '[]'::jsonb,
  blocked_hours jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.reservations (
  id text primary key default gen_random_uuid()::text,
  prestataire_id bigint not null references public.prestataires (id) on delete cascade,
  client_id uuid references auth.users (id) on delete set null,
  client_name text not null default '',
  client_first_name text not null default '',
  client_email text not null default '',
  client_phone text not null default '',
  service_id bigint,
  service_name text not null default '',
  date date not null,
  time text not null check (time ~ '^[0-2][0-9]:[0-5][0-9]$'),
  payment_method text not null default 'prestataire',
  status text not null default 'pending' check (status in ('pending', 'cancelled')),
  price jsonb,
  final_price jsonb,
  promo jsonb,
  reminder_email_id text,
  modified_at timestamptz,
  previous_slot jsonb,
  cancelled_at timestamptz,
  cancelled_by text,
  created_at timestamptz not null default now()
);

-- Un créneau ne peut être réservé qu'une fois (les rendez-vous annulés libèrent le créneau)
create unique index if not exists reservations_slot_unique
  on public.reservations (prestataire_id, date, time) where status <> 'cancelled';
create index if not exists reservations_client_idx on public.reservations (client_id);

create table if not exists public.promo_codes (
  id text primary key default gen_random_uuid()::text,
  code text not null unique,
  kind text not null default 'promo' check (kind in ('promo', 'parrainage')),
  prestataire_id bigint references public.prestataires (id) on delete cascade,
  client_id uuid references auth.users (id) on delete cascade,
  type text not null check (type in ('percent', 'amount')),
  value numeric not null check (value > 0),
  service_ids jsonb not null default '[]'::jsonb,
  start_date date,
  end_date date,
  max_uses integer check (max_uses is null or max_uses > 0),
  one_per_client boolean not null default false,
  used_count integer not null default 0,
  used_by jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending', 'active', 'disabled')),
  created_at timestamptz not null default now(),
  check (type <> 'percent' or value <= 100)
);

-- Réglages de la plateforme (une seule ligne)
create table if not exists public.settings (
  id integer primary key default 1 check (id = 1),
  referral jsonb not null default '{"enabled": false, "refereeReward": {"type": "percent", "value": 10}, "sponsorReward": {"type": "percent", "value": 10}}'::jsonb
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

