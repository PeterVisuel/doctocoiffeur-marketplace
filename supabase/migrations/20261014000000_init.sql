-- Créneaux déjà pris chez un prestataire (sans aucune information sur les clients)
create or replace function public.booked_slots(p_prestataire_id bigint)
returns table (date date, "time" text) language sql stable security definer set search_path = public as $$
  select r.date, r.time from public.reservations r
  where r.prestataire_id = p_prestataire_id and r.status <> 'cancelled'
    and r.date >= (now() at time zone 'Europe/Paris')::date - 1;
$$;

-- Connexion : distinguer « e-mail inconnu » de « mot de passe incorrect »
create or replace function public.email_status(p_email text)
returns text language sql stable security definer set search_path = public as $$
  select case when exists (select 1 from public.profiles where email = lower(trim(p_email)))
    then 'exists' else 'unknown' end;
$$;

create or replace function public.referral_code_exists(p_code text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where upper(referral_code) = upper(trim(p_code)));
$$;

-- Vérifie un code promo avant la réservation (aperçu du prix réduit)
create or replace function public.check_promo(p_code text, p_prestataire_id bigint, p_service_id bigint)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  pc public.promo_codes;
  err text;
begin
  if trim(coalesce(p_code, '')) = '' then return jsonb_build_object('error', 'Saisissez un code'); end if;
  select * into pc from public.promo_codes where code = upper(regexp_replace(p_code, '\s', '', 'g'));
  err := public.promo_error(pc, p_prestataire_id, p_service_id, auth.uid());
  if err is not null then return jsonb_build_object('error', err); end if;
  return jsonb_build_object('promo', jsonb_build_object(
    'id', pc.id, 'code', pc.code, 'kind', pc.kind, 'type', pc.type, 'value', pc.value));
end;
$$;

-- Réserver : le prix, le code promo et le créneau sont vérifiés par la base
create or replace function public.book_reservation(
  p_prestataire_id bigint, p_service_id bigint, p_date date, p_time text,
  p_client_name text, p_client_first_name text, p_client_email text, p_client_phone text,
  p_promo_code text default null
) returns public.reservations language plpgsql volatile security definer set search_path = public as $$
declare
  uid uuid := auth.uid();
  p public.prestataires;
  service jsonb;
  pc public.promo_codes;
  err text;
  min_price numeric;
  max_price numeric;
  result public.reservations;
  me public.profiles;
  referral jsonb;
begin
  if uid is null then raise exception 'Connectez-vous pour réserver'; end if;
  select * into p from public.prestataires where id = p_prestataire_id and approved;
  if p.id is null then raise exception 'Prestataire introuvable'; end if;
  select s into service from jsonb_array_elements(p.services) s where (s ->> 'id')::bigint = p_service_id;
  if service is null then raise exception 'Prestation introuvable'; end if;
  if p_time !~ '^[0-2][0-9]:[0-5][0-9]$' then raise exception 'Heure invalide'; end if;
  if public.appointment_at(p_date, p_time) <= now() then raise exception 'Ce créneau est déjà passé'; end if;
  if not public.slot_in_schedule(p.schedule, p_date, p_time) then
    raise exception 'Ce créneau ne fait pas partie des horaires du prestataire';
  end if;
  if trim(coalesce(p_client_name, '')) = '' or trim(coalesce(p_client_first_name, '')) = ''
    or trim(coalesce(p_client_email, '')) = '' or trim(coalesce(p_client_phone, '')) = '' then
    raise exception 'Remplissez vos coordonnées';
  end if;

  if trim(coalesce(p_promo_code, '')) <> '' then
    select * into pc from public.promo_codes where code = upper(regexp_replace(p_promo_code, '\s', '', 'g')) for update;
    err := public.promo_error(pc, p_prestataire_id, p_service_id, uid);
    if err is not null then raise exception 'Code promo refusé : %', err; end if;
  end if;

  min_price := (service ->> 'minPrice')::numeric;
  max_price := (service ->> 'maxPrice')::numeric;

  begin
    insert into public.reservations (
      prestataire_id, client_id, client_name, client_first_name, client_email, client_phone,
      service_id, service_name, date, time, price, final_price, promo
    ) values (
      p.id, uid, trim(p_client_name), trim(p_client_first_name), lower(trim(p_client_email)), trim(p_client_phone),
      p_service_id, service ->> 'name', p_date, p_time,
      jsonb_build_object('min', min_price, 'max', max_price),
      jsonb_build_object('min', public.apply_discount(min_price, pc.type, pc.value),
                         'max', public.apply_discount(max_price, pc.type, pc.value)),
      case when pc.id is null then null else jsonb_build_object('code', pc.code, 'kind', pc.kind, 'type', pc.type, 'value', pc.value) end
    ) returning * into result;
  exception when unique_violation then
    raise exception 'Ce créneau vient d''être réservé, choisissez-en un autre';
  end;

  if pc.id is not null then
    update public.promo_codes
      set used_count = used_count + 1, used_by = used_by || to_jsonb(uid::text)
      where id = pc.id;
  end if;

  -- Parrainage : le parrain reçoit son bon à la première réservation du filleul
  select * into me from public.profiles where id = uid;
  if me.referred_by is not null and not me.sponsor_rewarded then
    select s.referral into referral from public.settings s where s.id = 1;
    if coalesce((referral ->> 'enabled')::boolean, false) then
      perform public.create_referral_reward(me.referred_by, referral -> 'sponsorReward', 'PARRAIN');
    end if;
    update public.profiles set sponsor_rewarded = true where id = uid;
  end if;

  return result;
end;
$$;

-- Rend le code promo d'une réservation annulée
create or replace function public.release_promo(r public.reservations)
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  idx integer;
begin
  if r.promo is null then return; end if;
  select (t.ord - 1)::int into idx
  from public.promo_codes pc, jsonb_array_elements_text(pc.used_by) with ordinality as t(value, ord)
  where pc.code = r.promo ->> 'code' and t.value = r.client_id::text
  order by t.ord limit 1;
  update public.promo_codes
    set used_count = greatest(0, used_count - 1),
        used_by = case when idx is null then used_by else used_by - idx end
    where code = r.promo ->> 'code';
end;
$$;

-- Annuler (client : jusqu'à 24 h avant ; admin : à tout moment). Renvoie l'ancien identifiant de l'e-mail de rappel.
create or replace function public.cancel_reservation(p_id text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  r public.reservations;
  admin boolean := public.is_admin();
begin
  select * into r from public.reservations where id = p_id for update;
  if r.id is null or (r.client_id is distinct from auth.uid() and not admin) then
    raise exception 'Réservation introuvable';
  end if;
  if r.status = 'cancelled' then return jsonb_build_object('reminder_email_id', null); end if;
  if not admin and public.appointment_at(r.date, r.time) - now() <= interval '24 hours' then
    raise exception 'Moins de 24 h avant votre rendez-vous : contactez directement le prestataire.';
  end if;
  update public.reservations
    set status = 'cancelled', cancelled_at = now(), cancelled_by = case when admin then 'admin' else 'client' end,
        reminder_email_id = null
    where id = r.id;
  perform public.release_promo(r);
  return jsonb_build_object('reminder_email_id', r.reminder_email_id);
end;
$$;

-- Déplacer un rendez-vous (client : jusqu'à 24 h avant)
create or replace function public.move_reservation(p_id text, p_date date, p_time text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  r public.reservations;
  p public.prestataires;
  admin boolean := public.is_admin();
begin
  select * into r from public.reservations where id = p_id for update;
  if r.id is null or (r.client_id is distinct from auth.uid() and not admin) or r.status = 'cancelled' then
    raise exception 'Réservation introuvable';
  end if;
  if not admin and public.appointment_at(r.date, r.time) - now() <= interval '24 hours' then
    raise exception 'Moins de 24 h avant votre rendez-vous : contactez directement le prestataire.';
  end if;
  if p_time !~ '^[0-2][0-9]:[0-5][0-9]$' or public.appointment_at(p_date, p_time) <= now() then
    raise exception 'Ce créneau n''est pas disponible';
  end if;
  select * into p from public.prestataires where id = r.prestataire_id;
  if not public.slot_in_schedule(p.schedule, p_date, p_time) then
    raise exception 'Ce créneau n''est pas disponible';
  end if;
  begin
    update public.reservations
      set date = p_date, time = p_time, modified_at = now(),
          previous_slot = jsonb_build_object('date', r.date, 'time', r.time), reminder_email_id = null
      where id = r.id;
  exception when unique_violation then
    raise exception 'Ce créneau n''est pas disponible';
  end;
  return jsonb_build_object('reminder_email_id', r.reminder_email_id);
end;
$$;

-- Mémorise l'identifiant de l'e-mail de rappel programmé chez Resend
create or replace function public.set_reservation_reminder(p_id text, p_email_id text)
returns void language sql volatile security definer set search_path = public as $$
  update public.reservations set reminder_email_id = p_email_id
  where id = p_id and (client_id = auth.uid() or public.is_admin());
$$;

