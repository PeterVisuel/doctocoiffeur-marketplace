create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Vrai quand la requête vient directement du site (et non d'une fonction de ce script)
create or replace function public.from_client_request()
returns boolean language sql stable as $$
  select current_user in ('anon', 'authenticated');
$$;

create or replace function public.random_code(n integer)
returns text language sql volatile as $$
  select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', 1 + floor(random() * 32)::int, 1), '')
  from generate_series(1, n);
$$;

create or replace function public.make_referral_code(base text)
returns text language plpgsql volatile set search_path = public as $$
declare
  prefix text := left(regexp_replace(
    translate(upper(coalesce(base, '')), 'ÀÂÄÁÃÉÈÊËÍÌÎÏÓÒÔÖÕÚÙÛÜÇÑ', 'AAAAAEEEEIIIIOOOOOUUUUCN'),
    '[^A-Z]', '', 'g'), 6);
  candidate text;
begin
  if prefix = '' then prefix := 'CLIENT'; end if;
  loop
    candidate := prefix || '-' || public.random_code(4);
    exit when not exists (select 1 from public.profiles where referral_code = candidate);
  end loop;
  return candidate;
end;
$$;

create or replace function public.to_minutes(t text)
returns integer language sql immutable as $$
  select split_part(t, ':', 1)::int * 60 + coalesce(nullif(split_part(t, ':', 2), ''), '0')::int;
$$;

-- Heure de rendez-vous valide selon les horaires du prestataire (créneaux d'une heure)
create or replace function public.slot_in_schedule(p_schedule jsonb, p_date date, p_time text)
returns boolean language plpgsql immutable as $$
declare
  day_keys text[] := array['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'];
  day_key text := day_keys[extract(isodow from p_date)::int];
  minutes integer := public.to_minutes(p_time);
  has_any boolean;
begin
  select exists (
    select 1 from jsonb_each(coalesce(p_schedule, '{}'::jsonb)) d
    where jsonb_typeof(d.value) = 'array' and jsonb_array_length(d.value) > 0
  ) into has_any;
  -- Prestataire sans horaires renseignés : créneaux par défaut de 8 h à 19 h
  if not has_any then
    return minutes >= 8 * 60 and minutes <= 19 * 60 and minutes % 60 = 0;
  end if;
  return exists (
    select 1 from jsonb_array_elements(coalesce(p_schedule -> day_key, '[]'::jsonb)) s
    where minutes >= public.to_minutes(s ->> 'start')
      and minutes + 60 <= public.to_minutes(s ->> 'end')
      and (minutes - public.to_minutes(s ->> 'start')) % 60 = 0
  );
end;
$$;

-- Date et heure d'un rendez-vous, à l'heure de Paris
create or replace function public.appointment_at(p_date date, p_time text)
returns timestamptz language sql immutable as $$
  select (p_date + p_time::time) at time zone 'Europe/Paris';
$$;

create or replace function public.apply_discount(price numeric, discount_type text, discount_value numeric)
returns numeric language sql immutable as $$
  select case
    when discount_type is null then price
    when discount_type = 'percent' then round(price * (1 - discount_value / 100), 2)
    else greatest(0, round(price - discount_value, 2))
  end;
$$;

-- Raison pour laquelle un code n'est pas utilisable (null si le code est valable)
create or replace function public.promo_error(pc public.promo_codes, p_prestataire_id bigint, p_service_id bigint, p_client uuid)
returns text language plpgsql stable set search_path = public as $$
declare
  today date := (now() at time zone 'Europe/Paris')::date;
begin
  if pc.id is null then return 'Code inconnu'; end if;
  if pc.status = 'pending' then return 'Ce code n''est pas encore activé'; end if;
  if pc.status <> 'active' then return 'Ce code n''est plus actif'; end if;
  if pc.prestataire_id is not null and pc.prestataire_id <> p_prestataire_id then
    return 'Ce code n''est pas valable chez ce prestataire';
  end if;
  if jsonb_array_length(pc.service_ids) > 0 and not (pc.service_ids @> to_jsonb(p_service_id)) then
    return 'Ce code n''est pas valable pour cette prestation';
  end if;
  if pc.start_date is not null and today < pc.start_date then
    return 'Ce code sera valable à partir du ' || to_char(pc.start_date, 'YYYY-MM-DD');
  end if;
  if pc.end_date is not null and today > pc.end_date then return 'Ce code a expiré'; end if;
  if pc.max_uses is not null and pc.used_count >= pc.max_uses then
    return case when pc.client_id is not null then 'Ce bon a déjà été utilisé'
      else 'Ce code a atteint son nombre maximum d''utilisations' end;
  end if;
  if pc.client_id is not null and pc.client_id is distinct from p_client then
    return 'Ce bon est personnel : connectez-vous avec le compte concerné';
  end if;
  if pc.one_per_client then
    if p_client is null then return 'Connectez-vous à votre compte client pour utiliser ce code'; end if;
    if pc.used_by ? p_client::text then return 'Vous avez déjà utilisé ce code'; end if;
  end if;
  return null;
end;
$$;

-- Bon de réduction personnel (parrainage), utilisable une fois
create or replace function public.create_referral_reward(p_client uuid, p_reward jsonb, p_label text)
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  new_code text;
begin
  loop
    new_code := p_label || '-' || public.random_code(6);
    exit when not exists (select 1 from public.promo_codes where code = new_code);
  end loop;
  insert into public.promo_codes (code, kind, prestataire_id, client_id, type, value, max_uses, one_per_client, status)
  values (new_code, 'parrainage', null, p_client, p_reward ->> 'type', (p_reward ->> 'value')::numeric, 1, true, 'active');
end;
$$;

-- -------------------------------------------------------------------------------------
-- Création automatique du profil (et du salon pour un prestataire) à l'inscription
-- -------------------------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  new_role text := case when meta ->> 'role' = 'prestataire' then 'prestataire' else 'client' end;
  referral jsonb;
  sponsor uuid;
  sponsor_code text := upper(trim(coalesce(meta ->> 'referral_code', '')));
  category text := case when meta ->> 'category' = 'Artisans' then 'Artisans' else 'Beauté' end;
begin
  insert into public.profiles (id, role, email, first_name, last_name, phone, referral_code)
  values (
    new.id, new_role, lower(new.email),
    coalesce(meta ->> 'first_name', ''), coalesce(meta ->> 'last_name', ''), coalesce(meta ->> 'phone', ''),
    public.make_referral_code(coalesce(nullif(meta ->> 'first_name', ''), meta ->> 'name'))
  );

  if new_role = 'prestataire' then
    insert into public.prestataires (owner_id, name, city, category, email, approved, schedule)
    values (
      new.id, coalesce(nullif(meta ->> 'name', ''), 'Mon salon'), coalesce(meta ->> 'city', ''), category,
      lower(new.email), false,
      '{"monday":[{"start":"09:00","end":"18:00"}],"tuesday":[{"start":"09:00","end":"18:00"}],"wednesday":[{"start":"09:00","end":"18:00"}],"thursday":[{"start":"09:00","end":"18:00"}],"friday":[{"start":"09:00","end":"18:00"}],"saturday":[{"start":"10:00","end":"17:00"}],"sunday":[]}'::jsonb
    );
  elsif sponsor_code <> '' then
    -- Parrainage : le filleul reçoit son bon dès l'inscription (si le programme est actif)
    select s.referral into referral from public.settings s where s.id = 1;
    select id into sponsor from public.profiles where upper(referral_code) = sponsor_code and id <> new.id;
    if sponsor is not null and coalesce((referral ->> 'enabled')::boolean, false) then
      update public.profiles set referred_by = sponsor where id = new.id;
      perform public.create_referral_reward(new.id, referral -> 'refereeReward', 'BIENVENUE');
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- -------------------------------------------------------------------------------------
-- Protections : un utilisateur ne peut pas modifier certaines colonnes lui-même
-- -------------------------------------------------------------------------------------

create or replace function public.protect_profile()
returns trigger language plpgsql as $$
begin
  if public.from_client_request() and not public.is_admin() then
    new.role := old.role;
    new.email := old.email;
    new.referral_code := old.referral_code;
    new.referred_by := old.referred_by;
    new.sponsor_rewarded := old.sponsor_rewarded;
  end if;
  new.id := old.id;
  return new;
end;
$$;
drop trigger if exists protect_profile on public.profiles;
create trigger protect_profile before update on public.profiles
  for each row execute function public.protect_profile();

create or replace function public.protect_prestataire()
returns trigger language plpgsql as $$
begin
  if public.from_client_request() and not public.is_admin() then
    new.approved := old.approved;
    new.owner_id := old.owner_id;
  end if;
  return new;
end;
$$;
drop trigger if exists protect_prestataire on public.prestataires;
create trigger protect_prestataire before update on public.prestataires
  for each row execute function public.protect_prestataire();

-- Un code créé par un prestataire doit être activé par l'admin ; compteurs non modifiables
create or replace function public.protect_promo()
returns trigger language plpgsql as $$
begin
  if public.from_client_request() and not public.is_admin() then
    if tg_op = 'INSERT' then
      new.status := 'pending';
      new.kind := 'promo';
      new.client_id := null;
      new.used_count := 0;
      new.used_by := '[]'::jsonb;
    else
      new.status := old.status;
      new.used_count := old.used_count;
      new.used_by := old.used_by;
      new.kind := old.kind;
      new.client_id := old.client_id;
      new.prestataire_id := old.prestataire_id;
    end if;
  end if;
  new.code := upper(regexp_replace(new.code, '\s', '', 'g'));
  return new;
end;
$$;
drop trigger if exists protect_promo on public.promo_codes;
create trigger protect_promo before insert or update on public.promo_codes
  for each row execute function public.protect_promo();

